def get_admittance_matrix():
    """노드 어드미턴스 행렬 Y_bus [pu가 아닌 Ω^-1 단위] 반환."""
    Y = np.zeros((NUM_NODES, NUM_NODES), dtype=complex)
    for line in LINE_DATA:
        i, j = int(line[0]), int(line[1])
        y = 1.0 / complex(line[2], line[3])
        Y[i, i] += y
        Y[j, j] += y
        Y[i, j] -= y
        Y[j, i] -= y
    return Y


